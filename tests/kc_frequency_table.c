static int32_t reference_kc_to_fnum(int32_t kcode)
{
    int32_t kcode_h = (kcode >> 4) & 63;
    int32_t kcode_l = kcode & 15;
    int32_t i, slope, sum = 0;
    if (pg_freqtable[kcode_h].approxtype)
    {
        for (i = 0; i < 4; i++)
        {
            if (kcode_l & (1 << i))
            {
                sum += (pg_freqtable[kcode_h].slope >> (3 - i));
            }
        }
    }
    else
    {
        slope = pg_freqtable[kcode_h].slope | 1;
        if (kcode_l & 1)
        {
            sum += (slope >> 3) + 2;
        }
        if (kcode_l & 2)
        {
            sum += 8;
        }
        if (kcode_l & 4)
        {
            sum += slope >> 1;
        }
        if (kcode_l & 8)
        {
            sum += slope;
            sum++;
        }
        if ((kcode_l & 12) == 12 && (pg_freqtable[kcode_h].slope & 1) == 0)
        {
            sum += 4;
        }
    }
    return pg_freqtable[kcode_h].basefreq + (sum >> 1);
}


int main(void)
{
#ifdef GENERATE_TABLE
    puts("/* Generated by tests/kc_frequency_table.c with -DGENERATE_TABLE. */");
    puts("static const uint16_t pg_fnum_table[1024] = {");
    for (unsigned code = 0; code < 1024; code++)
    {
        int32_t value = reference_kc_to_fnum(code);
        assert(value >= 0 && value <= UINT16_MAX);
        if ((code & 15) == 0) printf("    ");
        printf("%d%s", value, code == 1023 ? "" : ",");
        printf("%s", (code & 15) == 15 ? "\n" : " ");
    }
    puts("};");
#else
    /* All 13-bit pitch codes, including the upper bits discarded by the ROM. */
    for (int32_t code = 0; code < 8192; code++)
        assert(OPM_KCToFNum(code) == reference_kc_to_fnum(code));
#endif
    return 0;
}
